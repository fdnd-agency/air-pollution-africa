        <h3>Measuring air pollution at street level</h3>

        <p>
            Air pollution in African cities is often poorly documented, 
            despite its major health impacts. To address this gap, 
            a measurement network was set up across Kumasi using low-cost diffusion tubes 
            that measure monthly average NO₂ concentrations. In 2025, 
            measurements were carried out at 20 locations across the city, 
            including traffic corridors, markets, residential areas, hospitals, 
            and urban background sites. This approach captures spatial differences 
            in exposure that are not visible in city-wide averages. 
            The measurements show that air pollution levels can vary strongly 
            within short distances, especially near busy roads and intersections.
        </p>
    </section>

